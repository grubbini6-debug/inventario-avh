export function drawAvhLogoVector(page:PDFPage,x:number,y:number,maxW:number,maxH:number){
  const scale=Math.min(maxW/SOURCE_W,maxH/SOURCE_H);
  const width=SOURCE_W*scale,height=SOURCE_H*scale;
  const left=x+(maxW-width)/2;
  const top=y+(maxH+height)/2;
  for(const path of GREEN_PATHS)page.drawSvgPath(path,{x:left,y:top,scale,color:AVH_GREEN});
  for(const path of WHITE_PATHS)page.drawSvgPath(path,{x:left,y:top,scale,color:WHITE});
  return{width,height};
}
